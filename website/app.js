const supportedLanguages = ['en', 'vi', 'zh-CN'];
const localized = (en, vi, zh) => ({ en, vi, 'zh-CN': zh })[currentLanguage];

const elements = [...document.querySelectorAll('[data-i18n]')];
const english = new Map(elements.map(element => [element.dataset.i18n, element.innerHTML]));
const attributeTranslations = ['alt', 'aria-label'].flatMap(attribute =>
  [...document.querySelectorAll(`[data-i18n-${attribute}]`)].map(element => ({
    element, attribute, key: element.getAttribute(`data-i18n-${attribute}`), english: element.getAttribute(attribute)
  }))
);
let currentLanguage = 'en';

function announce(message) {
  const region = document.getElementById('announcement');
  if (region) region.textContent = message;
}

function setLanguage(language, persist = false) {
  currentLanguage = supportedLanguages.includes(language) ? language : 'en';
  document.documentElement.lang = currentLanguage;
  const translations = currentLanguage === 'vi' ? vietnamese : currentLanguage === 'zh-CN' ? chinese : {};
  for (const element of elements) {
    const key = element.dataset.i18n;
    // Translations are fixed, trusted strings bundled with the website.
    element.innerHTML = translations[key] ?? english.get(key);
  }
  for (const { element, attribute, key, english } of attributeTranslations) {
    element.setAttribute(attribute, translations[key] ?? english);
  }
  for (const button of document.querySelectorAll('[data-lang]')) button.setAttribute('aria-pressed', String(button.dataset.lang === currentLanguage));
  // Keep explicit URL language choices when navigating between local pages.
  for (const link of document.querySelectorAll('a[href^="/"]')) {
    const url = new URL(link.getAttribute('href'), location.origin);
    if (url.origin !== location.origin) continue;
    url.searchParams.set('lang', currentLanguage);
    link.setAttribute('href', url.pathname + url.search + url.hash);
  }
  const privacy = location.pathname.includes('privacy');
  const usageGuide = location.pathname.endsWith('/usage.html');
  const skillsPage = location.pathname.endsWith('/skills.html');
  const metadata = skillsPage
    ? {
        title: currentLanguage === 'vi' ? 'No Short Skills — Skill viết và báo cáo công việc' : 'No Short Skills — Writing & work-report skills',
        description: currentLanguage === 'vi'
          ? 'Các skill viết và báo cáo cho Codex, Claude Code và AI agent khác. Giữ giọng văn và tổng hợp công việc từ hoạt động đã kiểm chứng.'
          : 'Reusable writing and work-report skills for Codex, Claude Code and other AI agents. Keep your voice and build reports from verified activity.'
      }
    : usageGuide
    ? {
        title: currentLanguage === 'vi' ? 'No Short Usage — Theo dõi chi phí và context trên macOS' : 'No Short Usage — Cost & context tracking for macOS',
        description: currentLanguage === 'vi'
          ? 'Theo dõi chi phí ước tính và context của Codex, Claude Code trên Mac. Tải No Short Usage, kết nối phiên và tùy chỉnh cảnh báo context.'
          : 'Track estimated Codex and Claude Code costs and context on your Mac. Download No Short Usage, set up sessions and customize context alerts.'
      }
    : privacy
    ? {
        title: currentLanguage === 'vi' ? 'Quyền riêng tư — no-short' : 'Privacy — no-short',
        description: currentLanguage === 'vi'
          ? 'Cách website no-short xử lý dữ liệu, lựa chọn ngôn ngữ và giao diện, dịch vụ lưu trữ cùng các liên kết ra ngoài.'
          : 'How the no-short website handles data, language and theme preferences, hosting and external links.'
      }
    : {
        title: currentLanguage === 'vi' ? 'No Short Usage — Theo dõi chi phí và context trên macOS' : 'No Short Usage — Cost & context tracking for macOS',
        description: currentLanguage === 'vi'
          ? 'Theo dõi chi phí ước tính và context của Codex, Claude Code ngay trên thanh menu Mac. Tải No Short Usage và theo dõi phiên chat.'
          : 'Track estimated Codex and Claude Code costs and context from your macOS menu bar. Download No Short Usage and follow your sessions.'
      };
  if (currentLanguage === 'zh-CN') {
    metadata.title = skillsPage ? 'No Short Skills — 写作与工作报告 skill' : privacy ? '隐私 — no-short' : 'No Short Usage — macOS 费用与上下文跟踪';
    metadata.description = skillsPage
      ? '适用于 Codex、Claude Code 及其他 AI agent 的写作与工作报告 skill。保留你的风格，用已核实的活动生成报告。'
      : privacy ? '了解 no-short 网站如何处理数据、语言和主题偏好、托管服务及外部链接。'
      : usageGuide ? '在 Mac 上查看 Codex 和 Claude Code 的预估费用及上下文用量。下载 No Short Usage，设置会话并自定上下文提醒。'
      : '在 macOS 菜单栏查看 Codex 和 Claude Code 的预估费用及上下文用量。下载 No Short Usage，跟踪聊天会话。';
  }
  document.title = metadata.title;
  document.querySelector('meta[name="description"]').content = metadata.description;
  for (const selector of ['meta[property="og:title"]', 'meta[name="twitter:title"]']) document.querySelector(selector).content = metadata.title;
  for (const selector of ['meta[property="og:description"]', 'meta[name="twitter:description"]']) document.querySelector(selector).content = metadata.description;
  document.querySelector('meta[property="og:locale"]').content = localized('en_US', 'vi_VN', 'zh_CN');
  const mainNav = document.querySelector('.desktop-nav');
  if (mainNav) mainNav.setAttribute('aria-label', localized('Main navigation', 'Điều hướng chính', '主导航'));
  const chart = document.querySelector('.chart');
  if (chart) chart.setAttribute('aria-label', localized('Illustrative seven-day usage chart, not live usage', 'Biểu đồ usage bảy ngày minh họa, không phải dữ liệu thực', '七天用量示意图，并非实时数据'));
  renderThemeControls();
  window.dispatchEvent(new CustomEvent('no-short-languagechange', { detail: currentLanguage }));
  if (persist) {
    try { localStorage.setItem('no-short-language', currentLanguage); } catch { /* Storage is optional. */ }
    const url = new URL(location.href);
    url.searchParams.set('lang', currentLanguage);
    history.replaceState(null, '', url);
    announce(localized('Switched to English.', 'Đã chuyển sang tiếng Việt.', '已切换为简体中文。'));
  }
}

function renderThemeControls() {
  const dark = document.documentElement.dataset.theme === 'dark';
  for (const button of document.querySelectorAll('[data-theme-toggle]')) {
    button.setAttribute('aria-pressed', String(dark));
    const action = dark
      ? localized('Switch to light mode', 'Chuyển sang chế độ sáng', '切换到浅色模式')
      : localized('Switch to dark mode', 'Chuyển sang chế độ tối', '切换到深色模式');
    button.setAttribute('aria-label', action);
    button.title = action;
    button.querySelector('[data-theme-label]').textContent = dark
      ? localized('Dark', 'Tối', '深色') : localized('Light', 'Sáng', '浅色');
  }
}
window.addEventListener('themechange', () => {
  renderThemeControls();
  announce(localized('Color theme changed.', 'Đã đổi chế độ hiển thị.', '已更改显示主题。'));
});

for (const button of document.querySelectorAll('[data-lang]')) button.addEventListener('click', () => setLanguage(button.dataset.lang, true));
let language = new URLSearchParams(location.search).get('lang');
if (!supportedLanguages.includes(language)) {
  try { language = localStorage.getItem('no-short-language'); } catch { language = 'en'; }
}
setLanguage(language);

