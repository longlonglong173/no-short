function announce(message) {
  const region = document.getElementById('announcement');
  if (region) region.textContent = message;
}

function resetCopy() {
  copyVersion++;
  clearTimeout(copyTimer);
  const label = document.querySelector('#copy-command [data-i18n]');
  if (label) label.textContent = currentLanguage === 'vi' ? 'Sao chép' : 'Copy';
}

function renderInstall() {
  const command = document.getElementById('install-command');
  if (!command) return;
  command.textContent = installCommands[currentInstall];
  document.getElementById('install-note').textContent = installNotes[currentLanguage][currentInstall];
  document.getElementById('command-label').textContent = currentInstall === 'claude' ? 'CLAUDE CODE' : 'TERMINAL';
  document.getElementById('install-panel').setAttribute('aria-labelledby', `tab-${currentInstall}`);
  for (const tab of document.querySelectorAll('[data-install]')) {
    const selected = tab.dataset.install === currentInstall;
    tab.setAttribute('aria-selected', String(selected));
    tab.tabIndex = selected ? 0 : -1;
  }
  resetCopy();
}

function setLanguage(language, persist = false) {
  currentLanguage = language === 'vi' ? 'vi' : 'en';
  document.documentElement.lang = currentLanguage;
  for (const element of elements) {
    const key = element.dataset.i18n;
    // Translations are fixed, trusted strings bundled with the website.
    element.innerHTML = currentLanguage === 'vi' ? (vietnamese[key] ?? english.get(key)) : english.get(key);
  }
  for (const button of document.querySelectorAll('[data-lang]')) button.setAttribute('aria-pressed', String(button.dataset.lang === currentLanguage));
  // Keep explicit URL language choices when navigating between local pages.
  for (const link of document.querySelectorAll('a[href^="/"]')) {
    const url = new URL(link.getAttribute('href'), location.origin);
    if (url.origin !== location.origin) continue;
    url.searchParams.set('lang', currentLanguage);
    link.setAttribute('href', url.pathname + url.search + url.hash);
  }
  const privacy = location.pathname.includes('privacy');
  const usageGuide = location.pathname.endsWith('/usage.html');
  document.title = usageGuide
    ? (currentLanguage === 'vi' ? 'No Short Usage — Cài đặt & trạng thái phát hành' : 'No Short Usage — Setup & release status')
    : privacy
    ? (currentLanguage === 'vi' ? 'Quyền riêng tư — no-short' : 'Privacy — no-short')
    : (currentLanguage === 'vi' ? 'no-short — Skill thiết thực cho AI agent.' : 'no-short — Practical skills for your AI agent.');
  if (usageGuide) document.querySelector('meta[name="description"]').content = currentLanguage === 'vi'
    ? 'Usage và context cục bộ trên macOS: trạng thái phát hành, cài đặt, kết nối Claude và cách gỡ.'
    : 'Local usage and context on macOS: release status, installation, Claude setup and removal.';
  else if (!privacy) document.querySelector('meta[name="description"]').content = currentLanguage === 'vi'
    ? 'Skill viết và báo cáo cho Codex, Claude Code cùng các AI agent. Giữ giọng văn, dựa trên bằng chứng và tìm hiểu công cụ theo dõi usage cục bộ. Dự án của Long.'
    : 'Reusable writing and reporting skills for Codex, Claude Code, and other AI agents. Keep your voice, write from evidence, and explore local usage tools. Built by Long.';
  const mainNav = document.querySelector('.desktop-nav');
  if (mainNav) mainNav.setAttribute('aria-label', currentLanguage === 'vi' ? 'Điều hướng chính' : 'Main navigation');
  const chart = document.querySelector('.chart');
  if (chart) chart.setAttribute('aria-label', currentLanguage === 'vi' ? 'Biểu đồ usage bảy ngày minh họa, không phải dữ liệu thực' : 'Illustrative seven-day usage chart, not live usage');
  renderInstall();
  renderThemeControls();
  if (persist) {
    try { localStorage.setItem('no-short-language', currentLanguage); } catch { /* Storage is optional. */ }
    const url = new URL(location.href);
    url.searchParams.set('lang', currentLanguage);
    history.replaceState(null, '', url);
    announce(currentLanguage === 'vi' ? 'Đã chuyển sang tiếng Việt.' : 'Switched to English.');
  }
}

function renderThemeControls() {
  const dark = document.documentElement.dataset.theme === 'dark';
  for (const button of document.querySelectorAll('[data-theme-toggle]')) {
    button.setAttribute('aria-pressed', String(dark));
    const action = currentLanguage === 'vi'
      ? (dark ? 'Chuyển sang chế độ sáng' : 'Chuyển sang chế độ tối')
      : (dark ? 'Switch to light mode' : 'Switch to dark mode');
    button.setAttribute('aria-label', action);
    button.title = action;
    button.querySelector('[data-theme-label]').textContent = currentLanguage === 'vi'
      ? (dark ? 'Tối' : 'Sáng') : (dark ? 'Dark' : 'Light');
  }
}
window.addEventListener('themechange', () => {
  renderThemeControls();
  announce(currentLanguage === 'vi' ? 'Đã đổi chế độ hiển thị.' : 'Color theme changed.');
});

for (const button of document.querySelectorAll('[data-lang]')) button.addEventListener('click', () => setLanguage(button.dataset.lang, true));
const tabs = [...document.querySelectorAll('[data-install]')];
for (const [index, tab] of tabs.entries()) {
  tab.addEventListener('click', () => { currentInstall = tab.dataset.install; renderInstall(); });
  tab.addEventListener('keydown', event => {
    let next;
    if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
    if (event.key === 'ArrowLeft') next = (index + tabs.length - 1) % tabs.length;
    if (event.key === 'Home') next = 0;
    if (event.key === 'End') next = tabs.length - 1;
    if (next === undefined) return;
    event.preventDefault();
    currentInstall = tabs[next].dataset.install;
    renderInstall();
    tabs[next].focus();
  });
}

document.getElementById('copy-command')?.addEventListener('click', async () => {
  const version = ++copyVersion;
  try {
    await navigator.clipboard.writeText(installCommands[currentInstall]);
    if (copyVersion !== version) return;
    document.querySelector('#copy-command [data-i18n]').textContent = currentLanguage === 'vi' ? 'Đã chép ✓' : 'Copied ✓';
    announce(currentLanguage === 'vi' ? 'Đã sao chép lệnh cài đặt.' : 'Installation command copied.');
    clearTimeout(copyTimer);
    copyTimer = setTimeout(resetCopy, 2400);
  } catch {
    if (copyVersion !== version) return;
    const command = document.getElementById('install-command');
    const selection = window.getSelection();
    const range = document.createRange();
    range.selectNodeContents(command);
    selection.removeAllRanges();
    selection.addRange(range);
    announce(currentLanguage === 'vi' ? 'Không thể truy cập clipboard. Lệnh đã được chọn để bạn sao chép thủ công.' : 'Clipboard unavailable. The command is selected for you to copy manually.');
    document.querySelector('#copy-command [data-i18n]').textContent = currentLanguage === 'vi' ? 'Chép thủ công' : 'Copy manually';
  }
});

let language = new URLSearchParams(location.search).get('lang');
if (language !== 'en' && language !== 'vi') {
  try { language = localStorage.getItem('no-short-language'); } catch { language = 'en'; }
}
setLanguage(language);
