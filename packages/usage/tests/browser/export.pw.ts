import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import fixture from '../fixtures/history-snapshot.json' with { type: 'json' };
const now = new Date('2026-10-01T12:00:00Z');
const data = () => ({ snapshot: structuredClone(fixture), selectedSession: null, requestedSessionId: null });
test('JSON download matches range/provider and omits identifiers until explicit opt-in', async ({ page }) => {
  const value = data(); await page.clock.install({ time: now });
  await page.route('**/__usage/snapshot', route => route.fulfill({ json: value }));
  await page.goto('/'); await page.getByRole('tab', { name: 'Lịch sử', exact: true }).click();
  await page.getByLabel('Công cụ lịch sử').selectOption('all');
  let waiting = page.waitForEvent('download'); await page.getByRole('button', { name: 'Xuất JSON', exact: true }).click();
  let download = await waiting, document = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(document.provider).toBe('all'); expect(document.timeZone).toBe('UTC');
  expect(document.aggregate.tokens.total).toBe(375); expect(document.aggregate.cost.amountUSD).toBe(7);
  expect(document.sessionReferences).toBeUndefined();
  expect(JSON.stringify(document)).not.toContain('codex-fixture');
  await page.getByLabel('Kèm tên/ID phiên (hoạt động cuối trong khoảng)').check();
  waiting = page.waitForEvent('download'); await page.getByRole('button', { name: 'Xuất JSON', exact: true }).click();
  download = await waiting; document = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(document.sessionReferences.scope).toBe('last-activity-in-range-not-cost-attribution');
  expect(document.sessionReferences.items.map((s: any) => s.id)).toContain('codex-fixture');
  await page.getByLabel('Công cụ lịch sử').selectOption('claude');
  waiting = page.waitForEvent('download'); await page.getByRole('button', { name: 'Xuất JSON', exact: true }).click();
  download = await waiting; document = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(document.aggregate.cost.amountUSD).toBe(5);
  expect(document.sessionReferences.items.every((s: any) => s.provider === 'claude')).toBe(true);
});
test('CSV download neutralizes formulas, preserves Unicode and missing history disables export', async ({ page }) => {
  const value: any = data();
  value.snapshot.history.days[0].aggregate.models[0].name = '=1+2';
  await page.clock.install({ time: now }); await page.route('**/__usage/snapshot', route => route.fulfill({ json: value }));
  await page.goto('/'); await page.getByRole('tab', { name: 'Lịch sử', exact: true }).click();
  await page.getByLabel('Công cụ lịch sử').selectOption('all');
  const waiting = page.waitForEvent('download'); await page.getByRole('button', { name: 'Xuất CSV', exact: true }).click();
  const csv = await readFile((await (await waiting).path())!, 'utf8');
  expect(csv).toContain("\"'=1+2\""); expect(csv).toContain('UTC'); expect(csv).not.toContain('sessionTitle');
  delete value.snapshot.history;
  await page.getByRole('button', { name: 'Cập nhật thống kê' }).click();
  await expect(page.getByRole('button', { name: 'Xuất CSV', exact: true })).toBeDisabled();
});
test('a legacy embedded host without download support gets an explicit error instead of a sandbox download', async ({ page }) => {
  const value = data();
  await page.clock.install({ time: now });
  await page.addInitScript(payload => { (window as any).openai = { toolResponseMetadata: { usage: payload }, callTool: async () => ({ _meta: { usage: payload } }) }; }, value);
  await page.route('**/embedded-host', route => route.fulfill({ contentType: 'text/html', body: '<iframe title="usage" src="/"></iframe>' }));
  await page.goto('/embedded-host');
  const frame = page.frameLocator('iframe');
  await frame.getByRole('tab', { name: 'Lịch sử', exact: true }).click();
  await frame.getByRole('button', { name: 'Xuất JSON', exact: true }).click();
  await expect(frame.getByRole('alert').filter({ hasText: 'host đã từ chối' })).toBeVisible();
});
test('export preserves stale status when refreshing retained history fails', async ({ page }) => {
  let failed = false; const value = data();
  await page.clock.install({ time: now });
  await page.route('**/__usage/snapshot', route => failed ? route.fulfill({ status: 500, body: '{}' }) : route.fulfill({ json: value }));
  await page.goto('/'); await page.getByRole('tab', { name: 'Lịch sử', exact: true }).click();
  failed = true; await page.getByRole('button', { name: 'Cập nhật thống kê' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Không cập nhật được thống kê' })).toBeAttached();
  const waiting = page.waitForEvent('download'); await page.getByRole('button', { name: 'Xuất JSON', exact: true }).click();
  const doc = JSON.parse(await readFile((await (await waiting).path())!, 'utf8'));
  expect(doc.status).toBe('stale');
});
