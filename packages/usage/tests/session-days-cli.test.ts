import { afterEach, expect, test } from 'bun:test';
import { existsSync } from 'node:fs';
import { mkdtemp, mkdir, writeFile, rm, copyFile, appendFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { runReport } from '../src/runner';
import { buildSnapshot } from '../src/adapter';
import { sessionUsageForRange } from '../src/history';
const binary = process.env.NO_SHORT_USAGE_CCUSAGE ?? new URL(`../runtime/darwin-${process.arch}/ccusage`, import.meta.url).pathname;
const dirs: string[] = [];
afterEach(async () => { await Promise.all(dirs.splice(0).map(dir => rm(dir, {recursive:true,force:true}))); });
const id = '11111111-1111-4111-8111-111111111111';
const line = (timestamp: string, n: number) => JSON.stringify({type:'event_msg', timestamp, payload:{type:'token_count',info:{last_token_usage:{input_tokens:n,cached_input_tokens:0,output_tokens:0,total_tokens:n}}}})+'\n';
test.skipIf(!existsSync(binary))('real reader ledger follows midnight/DST, canonical copied session+append, subagents and independent lifetime', async () => {
  const root = await mkdtemp(join(tmpdir(),'ns18-ledger-')); dirs.push(root);
  const logs=join(root,'codex'), copy=join(root,'copy'), claude=join(root,'claude');
  await Promise.all([mkdir(join(logs,'sessions'),{recursive:true}),mkdir(join(copy,'sessions'),{recursive:true}),mkdir(join(claude,'projects/p'),{recursive:true})]);
  const path=join(logs,'sessions/rollout-'+id+'.jsonl');
  const header = JSON.stringify({type:'session_meta',payload:{id,source:'cli',timestamp:'2026-11-01T03:59:00Z'}})+'\n'+JSON.stringify({type:'turn_context',payload:{model:'gpt-5'}})+'\n';
  await writeFile(path,header+line('2026-11-01T03:59:00Z',10)+line('2026-11-01T04:01:00Z',20)+line('2026-11-01T06:01:00Z',30));
  await copyFile(path,join(copy,'sessions/renamed-'+id+'.jsonl'));
  await appendFile(join(copy,'sessions/renamed-'+id+'.jsonl'),line('2026-11-03T04:00:00Z',40));
  await writeFile(join(logs,'sessions/child.jsonl'),JSON.stringify({type:'session_meta',payload:{id:'22222222-2222-4222-8222-222222222222',source:{subagent:{thread_spawn:{parent_thread_id:id}}}}})+'\n'+JSON.stringify({type:'turn_context',payload:{model:'gpt-5'}})+'\n'+line('2026-11-01T06:05:00Z',7));
  await writeFile(join(claude,'projects/p/claude-a.jsonl'),JSON.stringify({timestamp:'2026-11-01T04:02:00Z',sessionId:'claude-a',requestId:'req-a',message:{id:'msg-a',model:'claude-sonnet-4-20250514',usage:{input_tokens:12,output_tokens:3}}})+'\n');
  const scan = async (roots:string[]) => buildSnapshot(await runReport({binary,roots,claudeRoots:[claude],cacheDir:join(root,'cache'+roots.length),timeZone:'America/New_York',offline:true}),{now:new Date('2026-11-04T12:00:00Z'),timeZone:'America/New_York',metadata:new Map(),providers:['codex','claude']});
  const s=await scan([logs,copy]);
  expect(s.history?.sessionDays).toBeDefined();
  const oct=sessionUsageForRange(s,'codex','2026-10-31','2026-10-31')!;
  expect(oct.reconciled).toBe(true); expect(oct.aggregate.tokens.total).toBe(10);
  const nov=sessionUsageForRange(s,'codex','2026-11-01','2026-11-01')!;
  expect(nov.reconciled).toBe(true); expect(nov.aggregate.tokens.total).toBe(57); expect(nov.sessions).toHaveLength(2);
  expect(sessionUsageForRange(s,'claude','2026-11-01','2026-11-01')!.aggregate.tokens.total).toBe(15);
  expect(s.history!.sessionDays!.filter(r=>r.provider==='claude').every(r=>r.sessionId.startsWith('claude:'))).toBe(true);
  const reversed=await scan([copy,logs]);
  expect(reversed.history?.sessionDays).toEqual(s.history?.sessionDays);
  expect(sessionUsageForRange(s,'all','2026-11-01','2026-11-01')!.reconciled).toBe(true);
},30000);
